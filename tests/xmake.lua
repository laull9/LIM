rule("lim.database_test")
    on_test(function (target, opt)
        local runner = path.join(os.scriptdir(), "integration", "run_storage.py")
        local backend = path.filename(opt.name)
        local argv = {"-B", runner, backend, path.absolute(target:targetfile())}
        table.join2(argv, opt.runargs or {})
        return os.execv("python3", argv, {try = true}) == 0
    end)

target("lim_frame_test")
    set_kind("binary")
    set_default(false)
    set_group("tests/unit")
    set_languages("cxx23")
    set_warnings("allextra", "pedantic")
    add_deps("lim_core")
    add_files("support/*.cppm", "unit/*.cppm")
    add_tests("frame")

target("lim_storage_test")
    set_kind("binary")
    set_default(false)
    set_group("tests/integration")
    set_languages("cxx23")
    set_warnings("allextra", "pedantic")
    add_deps("lim_storage")
    add_files("support/*.cppm", "integration/*.cppm")
    add_tests("sqlite", "postgresql")
    add_rules("lim.database_test")
